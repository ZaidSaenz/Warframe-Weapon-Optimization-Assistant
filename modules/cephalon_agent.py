class WeaponDatabase:
    """
    Load weapons.json and create an in-memory name index.

    With ~654 canonical weapons this intentionally remains simple. No vector
    database or persistent search index is necessary for the current scope.
    """

    def __init__(self, path: Path = DATABASE_PATH):
        self.path = path

        if not self.path.exists():
            raise FileNotFoundError(
                f"Weapon database not found: {self.path}"
            )

        with self.path.open(
            "r",
            encoding="utf-8",
        ) as file:
            payload = json.load(file)

        self.schema_version = (
            payload.get("schema_version")
            if isinstance(payload, dict)
            else None
        )

        self.weapons = self._extract_weapons(payload)

        if not self.weapons:
            raise ValueError(
                "The weapon database contains no usable weapons."
            )

        self.index: dict[str, dict[str, Any]] = {}

        for weapon in self.weapons:
            name = self._weapon_name(weapon)

            if not isinstance(name, str):
                continue

            key = normalize_name(name)

            if key:
                self.index[key] = weapon

        if not self.index:
            raise ValueError(
                "Could not create the weapon name index."
            )

    @staticmethod
    def _weapon_name(
        weapon: dict[str, Any],
    ) -> str | None:
        identity = weapon.get("identity")

        if isinstance(identity, dict):
            name = identity.get("name")

            if isinstance(name, str):
                return name

        name = weapon.get("name")

        if isinstance(name, str):
            return name

        return None

    @staticmethod
    def _extract_weapons(
        payload: Any,
    ) -> list[dict[str, Any]]:
        if isinstance(payload, list):
            return [
                item
                for item in payload
                if isinstance(item, dict)
            ]

        if isinstance(payload, dict):
            weapons = payload.get("weapons")

            if isinstance(weapons, dict):
                return [
                    weapon
                    for weapon in weapons.values()
                    if isinstance(weapon, dict)
                ]

            if isinstance(weapons, list):
                return [
                    weapon
                    for weapon in weapons
                    if isinstance(weapon, dict)
                ]

        raise ValueError(
            "Unsupported weapons.json structure."
        )

    def _not_found(
        self,
        weapon_name: str,
    ) -> dict[str, Any]:
        query = normalize_name(weapon_name)

        matches = difflib.get_close_matches(
            query,
            list(self.index.keys()),
            n=5,
            cutoff=0.55,
        )

        suggestions = [
            self._weapon_name(self.index[key])
            for key in matches
        ]

        return {
            "found": False,
            "query": weapon_name,
            "suggestions": suggestions,
        }

    def _exact_weapon(
        self,
        weapon_name: str,
    ) -> dict[str, Any] | None:
        return self.index.get(
            normalize_name(weapon_name)
        )

    # --------------------------------------------------------
    # TOOL 1 — exact canonical weapon
    # --------------------------------------------------------

    def get_weapon(
        self,
        weapon_name: str,
    ) -> dict[str, Any]:
        weapon = self._exact_weapon(
            weapon_name
        )

        if weapon is None:
            return self._not_found(
                weapon_name
            )

        return {
            "found": True,
            "query": weapon_name,
            "weapon": weapon,
        }

    # --------------------------------------------------------
    # TOOL 2 — relative profile
    # --------------------------------------------------------

    def get_weapon_profile(
        self,
        weapon_name: str,
    ) -> dict[str, Any]:
        weapon = self._exact_weapon(
            weapon_name
        )

        if weapon is None:
            return self._not_found(
                weapon_name
            )

        name = self._weapon_name(weapon)
        metrics = weapon_metric_map(weapon)

        strengths: list[dict[str, Any]] = []
        weaknesses: list[dict[str, Any]] = []
        typical: list[dict[str, Any]] = []

        for metric_key, snapshot in metrics.items():
            definition = METRIC_BY_KEY[
                metric_key
            ]

            item = dict(snapshot)
            score = metric_desirability_score(
                snapshot,
                definition,
            )

            if score is not None:
                item["relative_score"] = round(
                    score,
                    2,
                )

            bucket = profile_bucket(
                snapshot,
                definition,
            )

            if bucket == "strength":
                strengths.append(item)
            elif bucket == "weakness":
                weaknesses.append(item)
            else:
                typical.append(item)

        strengths.sort(
            key=lambda item: item.get(
                "relative_score",
                0,
            ),
            reverse=True,
        )

        weaknesses.sort(
            key=lambda item: item.get(
                "relative_score",
                100,
            )
        )

        classification = weapon.get(
            "classification",
            {},
        )

        return {
            "found": True,
            "query": weapon_name,
            "weapon": name,
            "category": (
                classification.get("category")
                if isinstance(classification, dict)
                else None
            ),
            "population": weapon.get("population"),
            "strengths": strengths,
            "weaknesses": weaknesses,
            "typical": typical,
            "note": (
                "Strengths and weaknesses are relative statistical "
                "extremes inside the weapon population, not a build "
                "recommendation or overall weapon rating."
            ),
        }

    # --------------------------------------------------------
    # TOOL 3 — compare exact weapons
    # --------------------------------------------------------

    def compare_weapons(
        self,
        weapon_names: list[str],
    ) -> dict[str, Any]:
        cleaned_names = [
            name.strip()
            for name in weapon_names
            if isinstance(name, str)
            and name.strip()
        ]

        if len(cleaned_names) < 2:
            return {
                "error": (
                    "compare_weapons requires at least two "
                    "weapon names."
                )
            }

        found: list[
            tuple[str, dict[str, Any]]
        ] = []
        missing: list[dict[str, Any]] = []

        for requested_name in cleaned_names:
            weapon = self._exact_weapon(
                requested_name
            )

            if weapon is None:
                missing.append(
                    self._not_found(
                        requested_name
                    )
                )
                continue

            canonical_name = (
                self._weapon_name(weapon)
                or requested_name
            )

            found.append(
                (canonical_name, weapon)
            )

        if len(found) < 2:
            return {
                "found": False,
                "requested": cleaned_names,
                "missing": missing,
                "error": (
                    "Fewer than two requested weapons were "
                    "found exactly."
                ),
            }

        metric_maps = {
            name: weapon_metric_map(weapon)
            for name, weapon in found
        }

        common_metrics = set.intersection(
            *(
                set(metrics)
                for metrics in metric_maps.values()
            )
        )

        comparison: dict[
            str,
            list[dict[str, Any]],
        ] = {}

        for metric_key in sorted(common_metrics):
            rows: list[dict[str, Any]] = []

            for weapon_name, _weapon in found:
                snapshot = metric_maps[
                    weapon_name
                ][metric_key]

                rows.append(
                    {
                        "weapon": weapon_name,
                        **snapshot,
                    }
                )

            comparison[metric_key] = rows

        return {
            "found": True,
            "requested": cleaned_names,
            "weapons_compared": [
                name
                for name, _weapon in found
            ],
            "missing": missing,
            "common_metrics": sorted(
                common_metrics
            ),
            "comparison": comparison,
            "note": (
                "Only population-evaluated metrics shared by all "
                "found weapons are compared."
            ),
        }

    # --------------------------------------------------------
    # TOOL 4 — deterministic discovery
    # --------------------------------------------------------

    def search_weapons(
        self,
        *,
        criteria: list[str],
        category: str | None = None,
        limit: int = 10,
    ) -> dict[str, Any]:
        clean_criteria = []

        for criterion in criteria:
            if (
                isinstance(criterion, str)
                and criterion in SEARCH_CRITERIA
                and criterion not in clean_criteria
            ):
                clean_criteria.append(
                    criterion
                )

        if not clean_criteria:
            return {
                "error": (
                    "search_weapons requires at least one supported "
                    "statistical criterion."
                ),
                "supported_criteria": SEARCH_CRITERION_NAMES,
            }

        if category == "any":
            category = None

        allowed_categories = {
            None,
            "primary",
            "secondary",
            "melee",
        }

        if category not in allowed_categories:
            return {
                "error": (
                    "Unsupported category. Use primary, secondary, "
                    "melee, or any."
                )
            }

        limit = max(
            1,
            min(int(limit), 20),
        )

        results: list[dict[str, Any]] = []

        for weapon in self.weapons:
            classification = weapon.get(
                "classification",
                {},
            )

            weapon_category = (
                classification.get("category")
                if isinstance(classification, dict)
                else None
            )

            if (
                category is not None
                and weapon_category != category
            ):
                continue

            metrics = weapon_metric_map(
                weapon
            )

            matched: list[dict[str, Any]] = []
            scores: list[float] = []
            failed = False

            for criterion in clean_criteria:
                (
                    metric_key,
                    numerical_direction,
                ) = SEARCH_CRITERIA[
                    criterion
                ]

                snapshot = metrics.get(
                    metric_key
                )

                if (
                    snapshot is None
                    or not criterion_matches(
                        snapshot,
                        numerical_direction,
                    )
                ):
                    failed = True
                    break

                matched.append(
                    {
                        "criterion": criterion,
                        **snapshot,
                    }
                )

                scores.append(
                    criterion_score(
                        snapshot,
                        numerical_direction,
                    )
                )

            if failed:
                continue

            name = self._weapon_name(
                weapon
            )

            if not isinstance(name, str):
                continue

            score = (
                sum(scores) / len(scores)
                if scores
                else 0.0
            )

            results.append(
                {
                    "weapon": name,
                    "category": weapon_category,
                    "match_score": round(
                        score,
                        2,
                    ),
                    "matched_criteria": matched,
                }
            )

        results.sort(
            key=lambda item: (
                -float(item["match_score"]),
                str(item["weapon"]).casefold(),
            )
        )

        return {
            "found": bool(results),
            "category": category or "any",
            "criteria": clean_criteria,
            "result_count": min(
                len(results),
                limit,
            ),
            "total_matches": len(results),
            "results": results[:limit],
            "note": (
                "Search uses canonical population bands only. "
                "The current database supports broad categories "
                "(primary/secondary/melee), not reliable firearm "
                "subtypes such as rifle versus shotgun."
            ),
        }

    def summary(self) -> dict[str, Any]:
        return {
            "database": str(self.path),
            "schema_version": self.schema_version,
            "weapons_loaded": len(self.weapons),
            "indexed_names": len(self.index),
            "tools": [
                "get_weapon",
                "get_weapon_profile",
                "compare_weapons",
                "search_weapons",
            ],
        }


