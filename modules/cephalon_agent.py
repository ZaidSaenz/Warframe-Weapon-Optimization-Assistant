"""
Cephalon Agent

Warframe AI agent with four deterministic weapon tools:

- get_weapon
    Exact canonical data, description, mechanics and alternate-fire records.
- get_weapon_profile
    Relative strengths / weaknesses of one exact weapon.
- compare_weapons
    Side-by-side comparison of 2+ exact weapons on common metrics.
- search_weapons
    Discover weapons from broad category + relative statistical criteria.

The canonical database remains the source of truth. This module does not
calculate population percentiles or invent weapon ratings; it only organizes
metadata already generated by weapon_database.py for tool-friendly use.
"""

