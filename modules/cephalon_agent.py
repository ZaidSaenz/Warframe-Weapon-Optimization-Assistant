def parse_qwen_tool_calls(
    content: Any,
) -> list[dict[str, Any]]:
    """
    Fallback for Qwen native XML-like tool calls.

    Normal OpenAI-style message["tool_calls"] always has priority.
    This parser runs only when llama-cpp-python leaves a native
    <tool_call> block inside message["content"].
    """

    if not isinstance(
        content,
        str,
    ):
        return []

    if "<tool_call>" not in content:
        return []

    call_pattern = re.compile(
        r"<tool_call>\s*"
        r"<function=([^>\s]+)>\s*"
        r"(.*?)"
        r"</function>\s*"
        r"</tool_call>",
        re.DOTALL,
    )

    parameter_pattern = re.compile(
        r"<parameter=([^>\s]+)>\s*"
        r"(.*?)"
        r"</parameter>",
        re.DOTALL,
    )

    tool_calls: list[
        dict[str, Any]
    ] = []

    for index, match in enumerate(
        call_pattern.finditer(
            content
        ),
        start=1,
    ):
        tool_name = (
            match.group(1).strip()
        )

        parameter_block = (
            match.group(2)
        )

        arguments: dict[
            str,
            Any,
        ] = {}

        for parameter_match in (
            parameter_pattern.finditer(
                parameter_block
            )
        ):
            key = (
                parameter_match
                .group(1)
                .strip()
            )

            raw_value = (
                parameter_match
                .group(2)
                .strip()
            )

            try:
                value = json.loads(
                    raw_value
                )

            except json.JSONDecodeError:
                value = raw_value

            arguments[
                key
            ] = value

        tool_calls.append(
            {
                "id":
                    f"qwen_native_{index}",

                "type":
                    "function",

                "function": {
                    "name":
                        tool_name,

                    "arguments":
                        json.dumps(
                            arguments,
                            ensure_ascii=False,
                        ),
                },
            }
        )

    return tool_calls


def parse_tool_arguments(
    raw_arguments: Any,
) -> dict[str, Any]:
    if isinstance(raw_arguments, dict):
        return raw_arguments

    if not isinstance(raw_arguments, str):
        raise ValueError(
            "Tool arguments must be JSON."
        )

    try:
        value = json.loads(raw_arguments)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Invalid tool arguments: {raw_arguments}"
        ) from exc

    if not isinstance(value, dict):
        raise ValueError(
            "Tool arguments must decode to an object."
        )

    return value



def execute_tool(
    database: WeaponDatabase,
    tool_name: str,
    arguments: dict[str, Any],
) -> dict[str, Any]:
    if tool_name == "get_weapon":
        weapon_name = arguments.get(
            "weapon_name"
        )

        if not isinstance(weapon_name, str):
            return {
                "error": (
                    "get_weapon requires a string 'weapon_name'."
                )
            }

        return database.get_weapon(
            weapon_name
        )

    if tool_name == "get_weapon_profile":
        weapon_name = arguments.get(
            "weapon_name"
        )

        if not isinstance(weapon_name, str):
            return {
                "error": (
                    "get_weapon_profile requires a string "
                    "'weapon_name'."
                )
            }

        return database.get_weapon_profile(
            weapon_name
        )

    if tool_name == "compare_weapons":
        weapon_names = arguments.get(
            "weapon_names"
        )

        if not isinstance(weapon_names, list):
            return {
                "error": (
                    "compare_weapons requires an array "
                    "'weapon_names'."
                )
            }

        if not all(
            isinstance(name, str)
            for name in weapon_names
        ):
            return {
                "error": (
                    "Every compare_weapons weapon name must be a string."
                )
            }

        return database.compare_weapons(
            weapon_names
        )

    if tool_name == "search_weapons":
        criteria = arguments.get(
            "criteria"
        )

        if not isinstance(criteria, list):
            return {
                "error": (
                    "search_weapons requires an array 'criteria'."
                )
            }

        category = arguments.get(
            "category"
        )

        if category is not None and not isinstance(
            category,
            str,
        ):
            return {
                "error": (
                    "search_weapons 'category' must be a string."
                )
            }

        limit = arguments.get(
            "limit",
            10,
        )

        if not isinstance(limit, int):
            return {
                "error": (
                    "search_weapons 'limit' must be an integer."
                )
            }

        return database.search_weapons(
            criteria=criteria,
            category=category,
            limit=limit,
        )

    return {
        "error": f"Unknown tool: {tool_name}"
    }


