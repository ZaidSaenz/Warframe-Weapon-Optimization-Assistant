def normalize_name(value: str) -> str:
    """Normalize a weapon name for deterministic lookup."""

    return " ".join(
        value.casefold().strip().split()
    )



def nested_dict(
    data: dict[str, Any],
    path: tuple[str, ...],
) -> dict[str, Any] | None:
    """Return a nested dictionary when every path component exists."""

    current: Any = data

    for key in path:
        if not isinstance(current, dict):
            return None
        current = current.get(key)

    if isinstance(current, dict):
        return current

    return None



def metric_snapshot(
    weapon: dict[str, Any],
    metric: MetricView,
) -> dict[str, Any] | None:
    """
    Read one tool-friendly metric from the canonical database.

    A metric is useful to profile/compare/search only when the database already
    contains population metadata for it. No percentile is calculated here.
    """

    stat: dict[str, Any] | None = None

    for path in metric.paths:
        candidate = nested_dict(
            weapon,
            path,
        )

        if (
            candidate is not None
            and isinstance(
                candidate.get("population_percentile"),
                (int, float),
            )
        ):
            stat = candidate
            break

    if stat is None:
        return None

    value: Any = None

    for value_key in metric.value_keys:
        if value_key in stat:
            value = stat.get(value_key)
            break

    return {
        "metric": metric.key,
        "value": value,
        "unit": metric.unit,
        "population_percentile": stat.get(
            "population_percentile"
        ),
        "relative_band": stat.get(
            "relative_band"
        ),
        "guide_tag": stat.get(
            "guide_tag"
        ),
        "relative_context": stat.get(
            "relative_context"
        ),
    }



def weapon_metric_map(
    weapon: dict[str, Any],
) -> dict[str, dict[str, Any]]:
    """Return all population-evaluated metrics available for one weapon."""

    metrics: dict[str, dict[str, Any]] = {}

    for definition in PROFILE_METRICS:
        snapshot = metric_snapshot(
            weapon,
            definition,
        )

        if snapshot is not None:
            metrics[definition.key] = snapshot

    return metrics



def metric_desirability_score(
    snapshot: dict[str, Any],
    definition: MetricView,
) -> float | None:
    """
    Convert percentile direction into a sorting score for profile presentation.

    This does NOT claim overall weapon quality. It only lets a deterministic
    profile put statistically favorable extremes before weaker ones.
    """

    percentile = snapshot.get(
        "population_percentile"
    )

    if not isinstance(percentile, (int, float)):
        return None

    if definition.higher_is_better:
        return float(percentile)

    return 100.0 - float(percentile)



def profile_bucket(
    snapshot: dict[str, Any],
    definition: MetricView,
) -> str:
    """Classify one relative metric as strength, weakness, or typical."""

    band = snapshot.get("relative_band")

    if band == "middle_range":
        return "typical"

    if band in HIGH_BANDS:
        return (
            "strength"
            if definition.higher_is_better
            else "weakness"
        )

    if band in LOW_BANDS:
        return (
            "weakness"
            if definition.higher_is_better
            else "strength"
        )

    return "typical"



def criterion_matches(
    snapshot: dict[str, Any],
    numerical_direction: str,
) -> bool:
    band = snapshot.get("relative_band")

    if numerical_direction == "high":
        return band in HIGH_BANDS

    if numerical_direction == "low":
        return band in LOW_BANDS

    return False



def criterion_score(
    snapshot: dict[str, Any],
    numerical_direction: str,
) -> float:
    percentile = snapshot.get(
        "population_percentile"
    )

    if not isinstance(percentile, (int, float)):
        return 0.0

    if numerical_direction == "high":
        return float(percentile)

    return 100.0 - float(percentile)


