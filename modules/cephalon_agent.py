class CephalonAgent:

    def __init__(
        self,
        database: WeaponDatabase,
        model_path: Path = MODEL_PATH,
        n_ctx: int = DEFAULT_N_CTX,
        n_threads: int = DEFAULT_THREADS,
        n_gpu_layers: int = DEFAULT_GPU_LAYERS,
        debug: bool = False,
    ):
        if Llama is None:
            raise ImportError(
                "llama-cpp-python is required to run the Cephalon model."
            )

        if not model_path.exists():
            raise FileNotFoundError(
                f"Model not found: {model_path}"
            )

        self.database = database
        self.debug = debug

        self.llm = Llama(
            model_path=str(model_path),
            n_ctx=n_ctx,
            n_threads=n_threads,
            n_gpu_layers=n_gpu_layers,
            chat_format="chatml-function-calling",
            verbose=False,
        )

    def ask(
        self,
        user_message: str,
    ) -> str:
        """
        Two-phase tool workflow.

        Phase 1:
            Qwen chooses among the four tools, or answers directly when no
            database lookup is needed.

        Phase 2:
            Requested deterministic tool calls are executed. Tools are then
            disabled and the model answers from the verified results.

        Keeping phase 2 tool-free prevents the recursive tool loop observed
        with the generic ChatML function-calling adapter.
        """

        messages: list[dict[str, Any]] = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": user_message,
            },
        ]

        response = self.llm.create_chat_completion(
            messages=messages,
            tools=TOOLS,
            tool_choice="auto",
            temperature=0.1,
            max_tokens=320,
        )

        message = response["choices"][0]["message"]

        tool_calls = (
            message.get("tool_calls")
            or []
        )

        if not tool_calls:
            content = message.get("content")

            if content:
                return content.strip()

            return (
                "The model returned neither a tool call nor a response."
            )

        retrieved_results: list[
            dict[str, Any]
        ] = []

        for tool_call in tool_calls:
            function = tool_call.get(
                "function",
                {},
            )

            tool_name = function.get(
                "name",
                "",
            )

            raw_arguments = function.get(
                "arguments",
                "{}",
            )

            try:
                arguments = parse_tool_arguments(
                    raw_arguments
                )

                if self.debug:
                    print(
                        "\n[CEPHALON TOOL CALL]"
                    )
                    print(
                        json.dumps(
                            {
                                "tool": tool_name,
                                "arguments": arguments,
                            },
                            indent=2,
                            ensure_ascii=False,
                        )
                    )

                result = execute_tool(
                    database=self.database,
                    tool_name=tool_name,
                    arguments=arguments,
                )

            except Exception as exc:
                arguments = {}
                result = {
                    "error": str(exc)
                }

            if self.debug:
                print("\n[TOOL RESULT]")
                print(
                    json.dumps(
                        result,
                        indent=2,
                        ensure_ascii=False,
                    )
                )

            retrieved_results.append(
                {
                    "tool": tool_name,
                    "arguments": arguments,
                    "result": result,
                }
            )

        tool_payload = json.dumps(
            retrieved_results,
            ensure_ascii=False,
        )

        final_system_prompt = (
            SYSTEM_PROMPT
            + "\n\n"
            + "Verified local database tool calls have already been "
              "completed for this turn. No tools are available during "
              "this phase. Answer the user's original question using only "
              "the retrieved information below. If the result is missing, "
              "ambiguous, empty, or insufficient, say that clearly instead "
              "of filling the gap with invented information."
        )

        final_messages: list[
            dict[str, Any]
        ] = [
            {
                "role": "system",
                "content": final_system_prompt,
            },
            {
                "role": "user",
                "content": user_message,
            },
            {
                "role": "user",
                "content": (
                    "Verified database result:\n"
                    "<tool_response>\n"
                    + tool_payload
                    + "\n</tool_response>\n\n"
                    "Now answer the original question."
                ),
            },
        ]

        final_response = self.llm.create_chat_completion(
            messages=final_messages,
            tools=None,
            tool_choice="none",
            temperature=0.1,
            max_tokens=640,
        )

        final_message = (
            final_response["choices"][0]["message"]
        )

        content = final_message.get(
            "content"
        )

        if content:
            return content.strip()

        return (
            "The model received the database result but produced no final answer."
        )


