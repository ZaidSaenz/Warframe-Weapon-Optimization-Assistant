def print_json(value: Any) -> None:
    print(
        json.dumps(
            value,
            indent=2,
            ensure_ascii=False,
        )
    )



def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Warframe Cephalon with deterministic weapon tools."
        )
    )

    parser.add_argument(
        "--database",
        type=Path,
        default=DATABASE_PATH,
    )

    parser.add_argument(
        "--model",
        type=Path,
        default=MODEL_PATH,
    )

    parser.add_argument(
        "--n-ctx",
        type=int,
        default=DEFAULT_N_CTX,
    )

    parser.add_argument(
        "--threads",
        type=int,
        default=DEFAULT_THREADS,
    )

    parser.add_argument(
        "--gpu-layers",
        type=int,
        default=DEFAULT_GPU_LAYERS,
    )

    parser.add_argument(
        "--debug",
        action="store_true",
    )

    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
    )

    # Backward-compatible direct get_weapon test.
    tool_parser = subparsers.add_parser(
        "tool",
        help="Directly test get_weapon without loading the language model.",
    )
    tool_parser.add_argument("weapon_name")

    profile_parser = subparsers.add_parser(
        "profile",
        help="Directly test get_weapon_profile.",
    )
    profile_parser.add_argument("weapon_name")

    compare_parser = subparsers.add_parser(
        "compare",
        help="Directly test compare_weapons.",
    )
    compare_parser.add_argument(
        "weapon_names",
        nargs="+",
    )

    search_parser = subparsers.add_parser(
        "search",
        help="Directly test search_weapons.",
    )
    search_parser.add_argument(
        "criteria",
        nargs="+",
        choices=SEARCH_CRITERION_NAMES,
    )
    search_parser.add_argument(
        "--category",
        choices=[
            "primary",
            "secondary",
            "melee",
            "any",
        ],
        default="any",
    )
    search_parser.add_argument(
        "--limit",
        type=int,
        default=10,
    )

    ask_parser = subparsers.add_parser(
        "ask",
        help="Ask the Cephalon a question.",
    )
    ask_parser.add_argument("message")

    subparsers.add_parser(
        "database",
        help="Show database/index/tool status.",
    )

    return parser



def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    database = WeaponDatabase(
        args.database
    )

    if args.command == "database":
        print_json(
            database.summary()
        )
        return

    if args.command == "tool":
        print_json(
            database.get_weapon(
                args.weapon_name
            )
        )
        return

    if args.command == "profile":
        print_json(
            database.get_weapon_profile(
                args.weapon_name
            )
        )
        return

    if args.command == "compare":
        print_json(
            database.compare_weapons(
                args.weapon_names
            )
        )
        return

    if args.command == "search":
        print_json(
            database.search_weapons(
                criteria=args.criteria,
                category=args.category,
                limit=args.limit,
            )
        )
        return

    if args.command == "ask":
        agent = CephalonAgent(
            database=database,
            model_path=args.model,
            n_ctx=args.n_ctx,
            n_threads=args.threads,
            n_gpu_layers=args.gpu_layers,
            debug=args.debug,
        )

        answer = agent.ask(
            args.message
        )

        print("\nCEPHALON")
        print("========")
        print(answer)
        return


if __name__ == "__main__":
    main()
